// Authenticated QA member, real isolated backend. A separate mocked worker
// completes the queued job; this script never calls a real model/provider.
async page => {
  const url=new URL(page.url()),base=url.origin,group=url.searchParams.get('groupId');
  if(!group)throw Error('Open the QA group chat first');
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  const nav=page.getByRole('navigation',{name:'Các cuộc trò chuyện'});
  const field=page.getByRole('textbox',{name:'Tin nhắn cho Chatbot'});
  const noProvider=async p=>{if(/groq|runpod|deepseek|gpt-oss/i.test(await p.locator('body').innerText()))throw Error('Provider leaked into contestant UI');};
  await page.setViewportSize({width:1440,height:1000});
  await nav.getByRole('button',{name:/Câu hỏi đầu tiên của đội/}).waitFor({timeout:60000});
  await noProvider(page);
  await nav.getByRole('button',{name:/Câu hỏi đầu tiên của đội/}).click();
  await page.getByText('Phản hồi kiểm tra lịch sử',{exact:true}).waitFor();
  if((await page.getByRole('status',{name:'Token còn lại'}).innerText()).replace(/\D/g,'')!=='1970')throw Error('Wrong archived token ledger');
  await field.fill('Xin chào 😀');await page.getByText('10 ký tự',{exact:true}).waitFor();
  if(!await page.getByRole('button',{name:'Gửi tin nhắn',exact:true}).isDisabled())throw Error('Archive accepts a new prompt');
  await page.screenshot({path:'output/playwright/chat-history-desktop.png',fullPage:true});
  await page.reload();await page.getByText('Phản hồi kiểm tra lịch sử',{exact:true}).waitFor();
  await page.setViewportSize({width:390,height:844});
  if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1))throw Error('Mobile horizontal overflow');
  await page.waitForFunction(()=>document.querySelector('.chat-sidebar')?.getBoundingClientRect().right<=1);
  await page.screenshot({path:'output/playwright/chat-history-mobile.png',fullPage:true});
  await page.getByRole('button',{name:'Mở lịch sử trò chuyện'}).click();
  await nav.getByRole('button',{name:/Câu hỏi đầu tiên của đội/}).waitFor({state:'visible'});
  await page.waitForFunction(()=>document.querySelector('.chat-sidebar')?.getBoundingClientRect().left>=-1);
  await page.screenshot({path:'output/playwright/chat-history-mobile-sidebar.png',fullPage:true});
  await page.keyboard.press('Escape');
  await page.setViewportSize({width:1440,height:1000});
  await page.getByRole('button',{name:'Đoạn chat mới',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('.chat-token-badge strong')?.textContent?.replace(/\D/g,'')==='2000');
  const defaultId=await page.evaluate(k=>sessionStorage.getItem('arena-chat:group:'+k),group);
  let releaseAck;let posted;
  const acknowledged=new Promise(r=>posted=r);
  await page.route('**/api/workspace/chat',async route=>{
    if(route.request().method()!=='POST')return route.continue();
    const response=await route.fetch();if(response.status()!==202)throw Error('Prompt was not enqueued');
    await new Promise(r=>{releaseAck=r;posted();});await route.fulfill({response});
  });
  const prompt='Kiểm tra giao diện lưu lịch sử '+Date.now().toString().slice(-6);
  await field.fill(prompt);await page.getByRole('button',{name:'Gửi tin nhắn',exact:true}).click();
  await acknowledged;
  await nav.getByRole('button',{name:/Câu hỏi đầu tiên của đội/}).click();
  await page.getByText('Phản hồi kiểm tra lịch sử',{exact:true}).waitFor();
  releaseAck();
  await nav.getByRole('button',{name:new RegExp(prompt)}).waitFor({timeout:60000});
  if(await page.locator('.chat-messages').getByText(prompt,{exact:true}).count())throw Error('Late ACK overwrote the selected archive');
  await nav.getByRole('button',{name:new RegExp(prompt)}).click();
  await page.getByText('Phản hồi QA được lưu cho cả đội.',{exact:true}).waitFor({timeout:120000});
  await noProvider(page);
  await page.reload();await page.getByText('Phản hồi QA được lưu cho cả đội.',{exact:true}).waitFor();
  await page.screenshot({path:'output/playwright/chat-history-live.png',fullPage:true});
  const browser=page.context().browser();
  const teammate=await browser.newContext({storageState:'.local/history-qa-teammate-auth.json',viewport:{width:1440,height:1000}});
  const second=await teammate.newPage();await second.goto(url.href);
  await second.getByRole('navigation',{name:'Các cuộc trò chuyện'}).getByRole('button',{name:new RegExp(prompt)}).waitFor();
  const secondDefault=await second.evaluate(k=>sessionStorage.getItem('arena-chat:group:'+k),group);
  if(secondDefault===defaultId)throw Error('Independent browser reused the default conversation');
  if(await second.locator('.chat-message').count())throw Error('New browser inherited an automatic conversation');
  await second.getByRole('navigation',{name:'Các cuộc trò chuyện'}).getByRole('button',{name:new RegExp(prompt)}).click();
  await second.getByText('Phản hồi QA được lưu cho cả đội.',{exact:true}).waitFor();await noProvider(second);
  const outsider=await browser.newContext({storageState:'.local/history-qa-outsider-auth.json'});const third=await outsider.newPage();await third.goto(url.href);
  await third.getByText('Cuộc trò chuyện sẽ xuất hiện ở đây sau tin nhắn đầu tiên.',{exact:true}).waitFor();
  if(await third.locator('.chat-history-item').count())throw Error('Other team sees history');
  await teammate.close();await outsider.close();
  await page.unrouteAll({behavior:'wait'});
  if(errors.length)throw Error(errors.join('; '));
  await page.goto('about:blank');
  return {result:'PASS',realQaBackend:true,realProviderCalls:0,checks:['provider-free contestant UI','shared sidebar','archived usage','character count','archive read-only','reload selection','mobile drawer','new chat preserves history','late ACK fencing','queued response persisted','teammate sees history','independent default session','other team isolated']};
}
