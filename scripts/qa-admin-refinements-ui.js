/** Playwright CLI callback. Actual QA auth/quota; submission result and GPU provider are mocked. */
async page => {
  const base='http://localhost:3007', shots='output/playwright/admin-refinements-';
  const check=(value,message)=>{if(!value)throw new Error(message);};
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.context().clearCookies();
  await page.setViewportSize({width:1600,height:1050});
  await page.goto(base+'/login');
  await page.getByRole('button',{name:'Đăng ký',exact:true}).click();
  await page.getByRole('textbox',{name:'Email',exact:true}).waitFor();
  check(await page.locator('input[name=username]').getAttribute('type')==='email','Registration must use an email input');
  await page.screenshot({path:shots+'register-desktop.png',fullPage:true});
  await page.locator('.segmented').getByRole('button',{name:'Đăng nhập',exact:true}).click();
  await page.getByRole('textbox',{name:'Email hoặc tên đăng nhập',exact:true}).fill('qa_admin');
  await page.getByRole('textbox',{name:'Mật khẩu',exact:true}).fill('QA-Admin-Refinements-2026!');
  await page.locator('form').getByRole('button',{name:'Đăng nhập',exact:true}).click();
  await page.waitForURL(base+'/');
  await page.getByRole('heading',{name:'Phát hành vòng luyện',exact:true}).waitFor();
  const round=(await (await page.request.get(base+'/api/arena')).json()).rounds[0].id;
  let prefix=base+'/?round='+round;
  const visit=async section=>{
    await page.goto(prefix+'#'+section);
    await page.locator('main h1').waitFor();
    if(section==='admin')await page.getByRole('heading',{name:'Điều khiển vòng luyện',exact:true}).waitFor();
    if(section==='submit')await page.locator('.submission-history').waitFor();
    if(section==='workspace')await page.getByRole('heading',{name:'Dịch vụ trên Pod',exact:true}).waitFor();
    if(section==='leaderboard')await page.locator('.leaderboard tbody tr').waitFor();
  };
  const widths=await page.locator('.round-card').first().boundingBox();
  const publish=await page.locator('.publish-panel').boundingBox();
  check(Math.abs(widths.width-publish.width)<2,'Publish panel must match the round width');
  await page.screenshot({path:shots+'rounds-desktop.png',fullPage:true});
  await visit('overview');
  await page.locator('.task-card').first().waitFor();
  check(await page.locator('.admin-nav-link .nav-dot').count()===1,'Admin needs its attention marker');
  check(await page.getByRole('navigation',{name:'Điều hướng chính'}).getByRole('button',{name:'Nộp bài',exact:true}).locator('.nav-dot').count()===0,'Admin submit marker must be removed');
  check(await page.locator('.breadcrumbs a').innerText()==='Các vòng luyện','Keep return navigation in header');
  await visit('admin');
  const control=await page.locator('.round-control-panel').boundingBox(), config=await page.locator('.round-config-panel').boundingBox();
  check(control.width<config.width,'Configuration deserves more width than controls');
  const announcement=await page.locator('.admin-announcement-panel').boundingBox(), result=await page.locator('.admin-export-panel').boundingBox();
  check(result.width<announcement.width&&result.height<announcement.height,'Export panel must stay compact');
  await page.screenshot({path:shots+'admin-desktop.png',fullPage:true});
  await page.locator('.quota-grant select').selectOption('private');
  await page.locator('.quota-grant input').fill('3');
  const before=(await (await page.request.get(base+'/api/arena?round='+round)).json()).contest.privateLimit;
  const changed=page.waitForResponse(r=>r.url().includes('/api/admin/control')&&r.request().method()==='POST');
  await page.getByRole('button',{name:'Tăng quota',exact:true}).click();check((await changed).ok(),'Quota UI request failed');
  await page.getByRole('status').filter({hasText:'Đã tăng 3 lượt private'}).waitFor();
  const after=(await (await page.request.get(base+'/api/arena?round='+round)).json()).contest;
  check(after.privateLimit===before+3&&after.forcedEndAt===null&&after.privateAt===null,'Quota changed another round field');
  await visit('leaderboard');
  check(await page.locator('.leaderboard td.mono').first().evaluate(e=>Number(getComputedStyle(e).fontWeight))>=700,'Leaderboard scores need a fuller weight');
  await page.screenshot({path:shots+'leaderboard-desktop.png',fullPage:true});
  await visit('submit');
  check(!(await page.locator('.submission-history').innerText()).includes('Fixture reason'),'Invalid reason must not render in history');
  await page.getByRole('columnheader',{name:'Bản nộp/Thời gian',exact:true}).waitFor();
  for(const column of [2,3,4])check(await page.locator(`.submission-history tbody tr:first-child td:nth-child(${column})`).evaluate(e=>getComputedStyle(e).textAlign)==='center','Submission column must be centered');
  check(await page.locator('.submission-history th').first().evaluate(e=>parseFloat(getComputedStyle(e).fontSize))>=15,'Table header too small');
  await page.screenshot({path:shots+'history-desktop.png',fullPage:true});
  await page.route('**/api/submit?*',route=>route.fulfill({json:{id:'ui-mock',status:'accepted',score:29.74,metric:0.831}}));
  await page.getByRole('combobox',{name:'Tác vụ',exact:true}).selectOption('3');
  await page.locator('input[type=file]').setInputFiles('C:/CS_Major/Contest_2026/Olympic_AI/statements/Arena_02/web_ready/qa/jupyter_layout/data/public/Tac_vu_3/submission_public.csv');
  await page.locator('form').getByRole('button',{name:'Nộp bài',exact:true}).click();
  await page.getByRole('heading',{name:'Chấm bài thành công',exact:true}).waitFor();
  check(await page.locator('.result-score').evaluate(e=>parseFloat(getComputedStyle(e).fontSize))>=60,'Result score too small');
  await page.screenshot({path:shots+'submission-result-desktop.png',fullPage:true});
  const template={id:'00000000-0000-4000-8000-000000000040',name:'A40 · Môi trường luyện tập',gpuTypeId:'NVIDIA A40',cloudType:'SECURE',imageName:'example/workspace@sha256:qa',minRAMPerGPU:48,minVCPUPerGPU:8,containerDiskInGb:30,volumeInGb:100,sessionTokenLimit:2000,inputTokenLimit:1800,outputTokenLimit:1024};
  let templates=[template], saved=[];
  await page.route('**/api/workspace/**',async route=>{
    const path=new URL(route.request().url()).pathname;
    if(path.endsWith('/state'))return route.fulfill({json:{workspaces:[],templates,defaultTemplate:template,hasCredential:true,encryptionReady:true,teams:[{id:'qa-team',name:'Đội QA',members:1}],serverNow:Date.now()}});
    if(path.endsWith('/prices'))return route.fulfill({json:{gpus:[{id:'NVIDIA A40',name:'NVIDIA A40',memory:48,price:{secure:0.59,community:0.39}}],fetchedAt:Date.now()}});
    if(path.endsWith('/template')){const body=route.request().postDataJSON();saved.push(body);templates=templates.filter(t=>t.id!==body.id).concat([body]);return route.fulfill({json:{ok:true}});}
    throw new Error('Unexpected provider mutation: '+path);
  });
  await visit('workspace');
  const group=page.locator('.gpu-template-panel');
  await group.getByRole('spinbutton',{name:'Tổng token / phiên',exact:true}).waitFor();
  await page.screenshot({path:shots+'gpu-both-desktop.png',fullPage:true});
  await page.getByRole('button',{name:'Chỉ Chatbot',exact:false}).click();
  await group.getByRole('spinbutton',{name:'Tổng token / phiên',exact:true}).fill('2500');
  await group.getByRole('button',{name:'Lưu template',exact:true}).click();
  await page.getByRole('status').filter({hasText:'Đã lưu template'}).waitFor();
  check(saved.at(-1).services==='llm'&&saved.at(-1).sessionTokenLimit===2500,'Chat-only template not saved independently');
  await page.screenshot({path:shots+'gpu-chat-desktop.png',fullPage:true});
  await page.getByRole('button',{name:'Chỉ JupyterLab',exact:false}).click();
  check(await group.getByRole('spinbutton',{name:'Tổng token / phiên',exact:true}).count()===0,'Jupyter must hide chatbot limits');
  await group.getByRole('spinbutton',{name:'Workspace · GB',exact:true}).fill('120');
  await group.getByRole('button',{name:'Lưu template',exact:true}).click();
  await page.getByRole('status').filter({hasText:'Đã lưu template'}).waitFor();
  check(saved.at(-1).services==='jupyter'&&saved.at(-1).volumeInGb===120,'Jupyter-only template not saved independently');
  await page.screenshot({path:shots+'gpu-jupyter-desktop.png',fullPage:true});
  await page.getByRole('button',{name:'Chatbot + JupyterLab',exact:false}).click();
  check(await group.getByRole('spinbutton',{name:'Tổng token / phiên',exact:true}).inputValue()==='2000','Combined draft changed after switching services');
  await page.getByRole('button',{name:'Chỉ Chatbot',exact:false}).click();
  check(await group.getByRole('spinbutton',{name:'Tổng token / phiên',exact:true}).inputValue()==='2500','Chat-only draft was lost');
  await page.setViewportSize({width:390,height:844});
  for(const section of ['admin','leaderboard','submit','workspace']){
    await visit(section);
    check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),'Mobile overflow: '+section);
    await page.screenshot({path:shots+section+'-mobile.png',fullPage:true});
  }
  check(errors.length===0,'Browser errors: '+errors.join('; '));
  console.log('PASS desktop/mobile: table typography/alignment, hidden invalid reason, larger result/buttons, admin hierarchy/marker, real quota UI, email form, per-service template saves and draft retention. GPU and submission result mocked; no Pod allocated.');
}
